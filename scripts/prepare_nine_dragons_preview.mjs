import { readFileSync, writeFileSync } from 'node:fs';

// Đóng gói nguyên PNG aura để Canvas đọc pixel khi preview được mở bằng file://.
const root = new URL('../integration/task-009-nine-dragons/', import.meta.url);
const atlas = JSON.parse(readFileSync(new URL('atlas.json', root), 'utf8'));
const source = atlas.assets.aura.image;
const image = `data:image/png;base64,${readFileSync(new URL(source, root)).toString('base64')}`;
writeFileSync(new URL('review-aura.generated.js', root),
  `// Generated by scripts/prepare_nine_dragons_preview.mjs; giữ nguyên byte PNG nguồn.\nwindow.nineDragonsReviewAura=${JSON.stringify({ source, image })};\n`);
